-- Preparar un proyecto NUEVO para recibir una copia de seguridad.
--
-- Se corre en el SQL Editor del proyecto de DESTINO, despues de schema.sql y
-- todas las migraciones, y antes de scripts/restaurar-datos.mjs. Nunca en
-- produccion: borra todas las filas de todas las tablas.
--
-- Por que hace falta:
--   1. Las migraciones suelen cargar contenido de ejemplo (categorias,
--      planes, productos). La copia trae el contenido real del cliente con
--      sus propios ids: hay que empezar de cero o se mezclan.
--   2. Los triggers que ponen topes, recalculan totales o cuidan al
--      administrador estan pensados para el uso diario, no para cargar el
--      historial completo de una vez. Se apagan durante la carga.
--   3. Las columnas "generated always as identity" no dejan escribir su id,
--      y la copia trae los ids originales (otras tablas apuntan a ellos).
--      Durante la carga pasan a "by default" (ESCALA: bitacora).
-- supabase/restauracion/terminar.sql deshace los puntos 2 y 3 y adelanta los
-- contadores de ids.

create schema if not exists restauracion;
create table if not exists restauracion.identidades_always (tabla text, columna text);

do $$
declare
  t text;
  c record;
begin
  for t in select tablename from pg_tables where schemaname = 'public' loop
    execute format('truncate table public.%I cascade', t);
    execute format('alter table public.%I disable trigger user', t);
  end loop;

  for c in
    select table_name, column_name from information_schema.columns
    where table_schema = 'public' and is_identity = 'YES' and identity_generation = 'ALWAYS'
  loop
    insert into restauracion.identidades_always values (c.table_name, c.column_name);
    execute format('alter table public.%I alter column %I set generated by default', c.table_name, c.column_name);
  end loop;
end
$$;
